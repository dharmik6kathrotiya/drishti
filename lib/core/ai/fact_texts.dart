/// Localized templates for user-visible fact lines and for the concrete
/// sentences in rule-based answers. Keys starting with `f.` render facts,
/// `b.` build answer bodies. Missing keys fall back to English.
class FactTexts {
  FactTexts(this.lang) : _m = _packs[lang] ?? _en;

  final String lang;
  final Map<String, String> _m;

  String t(String key, [Map<String, String> values = const {}]) => fillTemplate(_m[key] ?? _en[key] ?? key, values);

  String month(int m) => t('m.$m');
  String monthYear(DateTime d) => t('f.my', {'month': month(d.month), 'year': '${d.year}'});
  String dayMonthYear(DateTime d) => t('f.dmy', {'d': '${d.day}', 'month': month(d.month), 'year': '${d.year}'});

  /// Every key of the English pack (for tests).
  static Iterable<String> get keys => _en.keys;
  static Map<String, String>? pack(String lang) => _packs[lang];
}

