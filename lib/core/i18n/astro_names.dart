/// Astrological names in each supported language and script.
///
/// English values are exactly what the engine produces, so English output is
/// unchanged. Other languages use the traditional names in their own script
/// (e.g. Tamil nakshatra names such as திருவாதிரை for Ardra).
class AstroNames {
  AstroNames._(this.lang, this._d);

  final String lang;
  final _Names _d;

  static final _cache = <String, AstroNames>{};

  static AstroNames of(String lang) => _cache.putIfAbsent(lang, () => AstroNames._(lang, _all[lang] ?? _all['en']!));

  bool get isEnglish => lang == 'en' || !_all.containsKey(lang);

  String planet(Planet p) => _d.planets[p.index];

  /// Short planet label used inside chart drawings.
  String planetAbbr(Planet p) => _d.planetAbbr[p.index];

  /// Western sign name (Aries...). Indian languages use the rashi name.
  String sign(Sign s) => _d.signs[s.index];

  String rashi(Sign s) => _d.rashis[s.index];

  /// Sign as shown in charts and tables. English keeps both names for Vedic
  /// ("Mesha (Aries)") and the glyph for Western ("♈ Aries").
  String signDisplay(Sign s, {required bool vedic}) {
    if (isEnglish) return vedic ? '${s.rashi} (${sign(s)})' : '${s.symbol} ${sign(s)}';
    return vedic ? rashi(s) : '${s.symbol} ${rashi(s)}';
  }

  String nakshatra(int index) => _d.nakshatras[index % 27];
  String nakshatraOf(Nakshatra n) => nakshatra(n.index);
  String nakshatraDeity(int index) => _d.deities[index % 27];

  /// Tithi name for tithi number 1..30 (without the paksha).
  String tithi(int n) {
    if (n == 15) return _d.purnima;
    if (n == 30) return _d.amavasya;
    return _d.tithis[(n - 1) % 15];
  }

  String paksha({required bool shukla}) => shukla ? _d.shukla : _d.krishna;

  /// Paksha from the engine's English label ('Shukla' / 'Krishna').
  String pakshaFromEnglish(String english) => paksha(shukla: english == 'Shukla');

  /// "Shukla Pratipada", "Krishna Amavasya" ...
  String tithiFull(int n) => '${paksha(shukla: n <= 15)} ${tithi(n)}';

  String yoga(int index) => _d.yogas[index % 27];

  /// Karana for karana number 1..60.
  String karana(int n) => _d.karanas[_karanaIndex(karanaName(n))];

  String vara(int weekday0) => _d.varas[weekday0 % 7];

  String month(int index, {bool adhika = false}) => (adhika ? _d.adhika : '') + _d.months[index % 12];

  /// Converts an engine month label ("Adhika Shravana", "Kartika").
  String monthFromEnglish(String english) {
    final adhika = english.startsWith('Adhika ');
    final base = adhika ? english.substring(7) : english;
    final i = lunarMonthNames.indexOf(base);
    return i < 0 ? english : month(i, adhika: adhika);
  }

  String choghadiya(ChoghadiyaKind k) => _d.choghadiya[k.index];

  /// Converts an engine Choghadiya label ("Amrit", "Rog" ...).
  String choghadiyaFromEnglish(String english) {
    final k = ChoghadiyaKind.values.where((c) => c.label == english).firstOrNull;
    return k == null ? english : choghadiya(k);
  }

  /// Converts an engine hora label (planet name, e.g. "moon").
  String horaFromEnglish(String english) {
    final p = Planet.values.where((x) => x.name == english).firstOrNull;
    return p == null ? english : planet(p);
  }

  /// Ascendant marker inside Indian chart drawings.
  String get ascAbbr => _ascAbbr[lang] ?? 'Asc';

  /// Centre title of a D1 chart drawing.
  String get rasiChart => _rasiChart[lang] ?? 'Rasi';

  /// Label for a chart drawn from the Moon (birth time unknown).
  String get moonChart => _moonChart[lang] ?? 'Moon chart';

  static const _ascAbbr = {'hi': 'ल', 'mr': 'ल', 'bn': 'ল', 'ta': 'லக்', 'te': 'ల', 'kn': 'ಲ', 'ml': 'ല'};
  static const _rasiChart = {
    'hi': 'राशि',
    'mr': 'राशी',
    'bn': 'রাশি',
    'ta': 'ராசி',
    'te': 'రాశి',
    'kn': 'ರಾಶಿ',
    'ml': 'രാശി',
  };
  static const _moonChart = {
    'hi': 'चंद्र कुंडली',
    'mr': 'चंद्र कुंडली',
    'bn': 'চন্দ্র কুণ্ডলী',
    'ta': 'சந்திர ஜாதகம்',
    'te': 'చంద్ర చక్రం',
    'kn': 'ಚಂದ್ರ ಕುಂಡಲಿ',
    'ml': 'ചന്ദ്ര ചാർട്ട്',
  };

  String get vikram => _d.vikram;
  String get shaka => _d.shaka;

  static const _karanaOrder = [
    'Bava',
    'Balava',
    'Kaulava',
    'Taitila',
    'Garaja',
    'Vanija',
    'Vishti',
    'Shakuni',
    'Chatushpada',
    'Naga',
    'Kimstughna',
  ];
  static int _karanaIndex(String english) => _karanaOrder.indexOf(english);

  /// Karana from the engine's English name.
  String karanaFromEnglish(String english) {
    final i = _karanaIndex(english);
    return i < 0 ? english : _d.karanas[i];
  }
}

